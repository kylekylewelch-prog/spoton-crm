import * as schema from '@/db/schema';

/**
 * The object registry.
 *
 * Every object in the CRM is described here once — its fields, their types, how
 * they relate to other objects, which are required, which are searchable, and what
 * a list view should show. The REST API, the generic list and detail screens, the
 * validation layer, the reporting engine and the MCP tools are all generated from
 * this metadata.
 *
 * That is what makes custom objects first-class rather than extra tables: adding an
 * entry below gives an object an API, a UI, validation, security, reporting and an
 * MCP surface without touching any of those layers.
 */

export type FieldType =
  | 'text'
  | 'textarea'
  | 'number'
  | 'money'
  | 'percent'
  | 'bps'
  | 'boolean'
  | 'date'
  | 'datetime'
  | 'enum'
  | 'reference'
  | 'json'
  | 'email'
  | 'phone'
  | 'url';

export type FieldDef = {
  name: string;
  label: string;
  type: FieldType;
  /** Referenced object key, for `reference` fields. */
  referenceTo?: string;
  options?: readonly string[];
  required?: boolean;
  /** Included in the default list view. */
  inList?: boolean;
  /** Free-text search targets this field. */
  searchable?: boolean;
  readOnly?: boolean;
  /** Shown on the detail page but not the edit form. */
  derived?: boolean;
  help?: string;
  section?: string;
};

export type RelatedListDef = {
  /** Object key of the child records. */
  object: string;
  /** Foreign key on the child pointing back at this object. */
  foreignKey: string;
  label: string;
  columns?: string[];
};

export type ObjectDef = {
  key: string;
  label: string;
  labelPlural: string;
  /** Drizzle table. */
  table: any;
  /** Field used as the record's display name. */
  nameField: string;
  /** Grouping for navigation. */
  group:
    | 'revenue'
    | 'customers'
    | 'demand'
    | 'commercial'
    | 'subscriptions'
    | 'success'
    | 'service'
    | 'partners'
    | 'platform';
  icon?: string;
  fields: FieldDef[];
  relatedLists?: RelatedListDef[];
  defaultSort?: { field: string; direction: 'asc' | 'desc' };
  /** Objects that must not be created or deleted through the generic API. */
  systemManaged?: boolean;
  description?: string;
};

