/* --------------------------------------------------------------------- helpers */

export function getObject(key: string): ObjectDef {
  const def = OBJECTS[key];
  if (!def) throw new Error(`Unknown object type: ${key}`);
  return def;
}

export function objectKeys(): string[] {
  return Object.keys(OBJECTS);
}

export function listFields(key: string): FieldDef[] {
  const def = getObject(key);
  const inList = def.fields.filter((x) => x.inList);
  return inList.length > 0 ? inList : def.fields.slice(0, 6);
}

export function searchableFields(key: string): FieldDef[] {
  return getObject(key).fields.filter((x) => x.searchable);
}

export function editableFields(key: string): FieldDef[] {
  return getObject(key).fields.filter((x) => !x.readOnly && !x.derived);
}

export function requiredFields(key: string): FieldDef[] {
  return getObject(key).fields.filter((x) => x.required);
}

export function fieldDef(key: string, field: string): FieldDef | undefined {
  return getObject(key).fields.find((x) => x.name === field);
}

export function objectsByGroup(): Record<string, ObjectDef[]> {
  const out: Record<string, ObjectDef[]> = {};
  for (const def of Object.values(OBJECTS)) {
    (out[def.group] ??= []).push(def);
  }
  for (const group of Object.keys(out)) {
    out[group].sort((a, b) => a.labelPlural.localeCompare(b.labelPlural));
  }
  return out;
}

